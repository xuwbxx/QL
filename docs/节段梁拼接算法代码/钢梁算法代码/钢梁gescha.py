# R 做权重，1最关心，0最不关心（参考point表里的R1sheet）
def gescha(P,Q,D,R):
    """
通过已完工的理论坐标和实测坐标对比得到矩阵映射关系，对待安装的理论坐标点位进行整体偏移及可能的旋转，得到待安装梁段预测坐标

需要参数: 
    假定已完工点位n个，待施工点位m个
    矩阵说明：行：x/y/z坐标轴；列：点位
    P: 已完工节段的理论坐标矩阵 (3, n) - 设计值（来自【钢梁管理-理论数据】）
    Q: 已完工节段的实测坐标矩阵 (3, n) - 实际测量值（来自【钢梁管理-实测数据】）
    D: 待安装节段的理论坐标矩阵 (3, m) - 设计值（需要预测实际位置）（来自【钢梁管理-理论数据】）
    R: 节段权重矩阵 (3, n) - 施工精度高的节段权重=1，精度低的权重<1（来自【钢梁管理-理论数据】）

主要步骤：
    1. 通过P*R，得到加权后的理论坐标
    2. 通过Q*R，得到加权后的实测坐标
    3. 

返回:
    D1: 待安装节段的预测实际坐标 (3, m)
    """
    
    # 获取点云维度信息
    # nrow=3 (X,Y,Z三个坐标方向)，ncol=已完工节段数量
    nrow, ncol = P.shape  # 矩阵.shape方法返回rowCount, colCount
    # nrow1=3，ncol1=待安装节段数量
    nrow1, ncol1 = D.shape  
    
    # --- 步骤1: 应用权重到坐标矩阵 ---
    # 施工中，某些节段可能测量精度高（如已精调），某些可能精度低（如临时支撑）
    # 通过权重矩阵R，让高精度节段在配准中起主导作用
    wP = P * R  # 加权后的理论坐标
    wQ = Q * R  # 加权后的实测坐标
    
    # --- 步骤2: 计算加权重心 ---
    # 计算"加权平均"位置，作为旋转中心
    # 权重越大，该节段对整体变换的影响越大
    G1 = np.sum(wP, axis=1) / np.sum(R, axis=1)  # 理论点云的加权重心
    G2 = np.sum(wQ, axis=1) / np.sum(R, axis=1)  # 实测点云的加权重心
    
    # --- 步骤3: 去中心化（将点云移到原点） ---
    # 目的是分离旋转和平移，使SVD只求解旋转部分
    # 相当于把所有节段相对于其重心进行定位
    PP = np.zeros((nrow, ncol))  # 去中心化的理论坐标
    QQ = np.zeros((nrow, ncol))  # 去中心化的实测坐标
    for i in range(3):  # X, Y, Z三个方向
        for j in range(ncol):  # 遍历每个已完工节段
            PP[i, j] = P[i, j] - G1[i]  # 理论值 - 理论重心
            QQ[i, j] = Q[i, j] - G2[i]  # 实测值 - 实测重心
    
    # --- 步骤4: 构建协方差矩阵 H ---
    # H = Σ(权重 * 理论偏差向量 * 实测偏差向量^T)
    # 这个矩阵包含了理论点云和实测点云之间的相关性
    # 施工中：反映了已完工节段的"理论→实测"变形模式
    PT = np.transpose(PP)  # 转为 (n, 3) 便于计算
    QT = np.transpose(QQ)  # 转为 (n, 3)
    
    H = (R * PP) @ QT  # H.shape = (3, 3) 协方差矩阵
    
    # --- 步骤5: 奇异值分解 (SVD) 求解最优旋转 ---
    # SVD分解 H = U * S * V^T
    # 通过SVD，可以找到最优旋转矩阵，使"理论点云旋转后"最接近"实测点云"
    # 这相当于求解施工中的"姿态偏差"（旋转角）
    U, S, VT = np.linalg.svd(H)  # U: (3,3), S: (3,), VT: (3,3)
    V = np.transpose(VT)  # V = VT^T，得到 (3,3)
    UT = np.transpose(U)  # U^T
    
    # --- 步骤6: 计算旋转矩阵 R ---
    # 此处R开始，是指旋转矩阵，不再是前面的权重矩阵
    # R = V * U^T 是最优旋转矩阵（最小二乘意义下）
    R = np.dot(V, UT)  # 初始旋转矩阵 (3,3)
    det_R = np.linalg.det(R)  # 检查行列式，判断是否包含镜像翻转
    
    # --- 步骤7: 反射检测与修正 ---
    # 桥梁施工中，理论上不应该出现镜像翻转（左右手坐标系变换）
    # 如果出现 det_R < 0，说明SVD求出了包含反射的解
    # 需要修正为纯旋转（避免出现"翻转"这种不合理的变换）
    cha = np.diag([1, 1, -1])  # 反射检测矩阵
    
    T = np.zeros((3, ncol1))  # 初始化平移矩阵
    
    if det_R > 0:
        # 正常情况：纯旋转，直接使用
        # 平移量 = 实测重心 - 旋转后的理论重心
        t = G2 - np.dot(R, G1)
    else:
        # 异常情况：出现反射，需要修正
        # 将V的第三列取反，消除反射成分
        RR = np.dot(V, cha)  # 修正V
        R = np.dot(RR, UT)   # 重新计算旋转矩阵（保证det_R>0）
        t = G2 - np.dot(R, G1)  # 重新计算平移量
    
    # --- 步骤8: 构建平移矩阵 ---
    # 将所有待安装节段使用相同的平移量
    # 施工中：相当于"整体平移"所有剩余节段
    for i in range(3):  # X, Y, Z三个方向
        for j in range(ncol1):  # 遍历每个待安装节段
            T[i, j] = t[i]  # 每个节段平移相同的量
    
    # --- 步骤9: 应用到待安装节段 ---
    # D1 = R * D + T
    # 即：待安装节段的预测实际坐标 = 旋转 * 理论坐标 + 平移
    # 这就是通过已完工节段的偏差，预测未完工节段的实际安装位置
    D1 = np.dot(R, D) + T
    
    return D1